/**
 * Generates the seed migration for the starter guides from src/lib/guides/starter.ts.
 * Run once:  bun scripts/guides-to-sql.ts > prisma/migrations/<timestamp>_seed_guides/migration.sql
 * Safe to apply on any database: existing guides (same slug) are left untouched.
 */
import { STARTER_GUIDES } from "../src/lib/guides/starter";

const q = (s: string | null) => (s === null ? "NULL" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `ARRAY[${a.map(q).join(", ")}]::text[]` : "ARRAY[]::text[]");

const rows = STARTER_GUIDES.map((g) => `(
  ${q(`guide-${g.slug}`)}, ${q(g.slug)}, ${q(g.title)}, ${q(g.summary)},
  ${g.category ? `(SELECT id FROM "ServiceCategory" WHERE slug = ${q(g.category)})` : "NULL"},
  ${q(g.audience)}::"GuideAudience", ${q(g.body)},
  ${g.prices.length ? `${q(JSON.stringify(g.prices))}::jsonb` : "NULL"}, ${q(g.pricesNote)},
  ${arr(g.questions)}, ${arr(g.redFlags)}, ${arr(g.checklist)},
  'PUBLISHED'::"GuideStatus", CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
)`);

console.log(`-- Starter hiring guides (generated by scripts/guides-to-sql.ts from src/lib/guides/starter.ts).
-- Existing guides with the same slug are kept as they are, so admin edits are never overwritten.
INSERT INTO "Guide" ("id", "slug", "title", "summary", "categoryId", "audience", "body", "prices", "pricesNote",
  "questions", "redFlags", "checklist", "status", "publishedAt", "updatedAt")
VALUES
${rows.join(",\n")}
ON CONFLICT ("slug") DO NOTHING;`);
